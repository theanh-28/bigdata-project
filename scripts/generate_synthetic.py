from __future__ import annotations

import argparse
import json
import random
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

ATTRS = [
    ("RestaurantsTakeOut", 0.72, [True, False]),
    ("RestaurantsDelivery", 0.58, [True, False]),
    ("OutdoorSeating", 0.31, [True, False]),
    ("WiFi", 0.42, ["free", "paid", "no"]),
    ("BusinessParking", 0.63, [{"garage": False, "street": True}, {"garage": True, "street": False}]),
    ("Alcohol", 0.24, ["none", "beer_and_wine", "full_bar"]),
    ("GoodForKids", 0.38, [True, False]),
    ("WheelchairAccessible", 0.18, [True, False]),
    ("NoiseLevel", 0.22, ["quiet", "average", "loud"]),
    ("RestaurantsReservations", 0.44, [True, False]),
    ("HasTV", 0.26, [True, False]),
    ("DogsAllowed", 0.13, [True, False]),
    ("DriveThru", 0.08, [True, False]),
    ("HappyHour", 0.11, [True, False]),
    ("Corkage", 0.05, [True, False]),
    ("BYOB", 0.035, [True, False]),
    ("Music", 0.14, [{"live": True}, {"background": True}]),
    ("DietaryOptions", 0.17, [{"vegan": True}, {"gluten_free": True}, {"vegetarian": True}]),
    ("PaymentOptions", 0.61, [{"credit_cards": True}, {"cash_only": True}]),
    ("ParkingDetails", 0.29, [{"lot": True}, {"street": True}, {"valet": True}]),
    ("DeliveryPartners", 0.16, ["A", "B", "C"]),
    ("OpenLate", 0.09, [True, False]),
]


def main() -> None:
    p = argparse.ArgumentParser(description="Generate explicitly simulated JSONL data for MongoDB experiments.")
    p.add_argument("--businesses", type=int, default=20000)
    p.add_argument("--reviews", type=int, default=500000)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--outdir", default=str(ROOT / "data" / "generated"))
    args = p.parse_args()
    if args.businesses < 1 or args.reviews < 1:
        p.error("--businesses and --reviews must be positive")
    rng = random.Random(args.seed)
    out = Path(args.outdir)
    out.mkdir(parents=True, exist_ok=True)
    business_ids = [f"SYNB{i:08d}" for i in range(args.businesses)]
    cities = [("Phoenix", "AZ"), ("Las Vegas", "NV"), ("Toronto", "ON"), ("Charlotte", "NC"), ("Pittsburgh", "PA")]
    categories = ["Restaurants", "Coffee & Tea", "Food", "Bars", "Shopping", "Bakeries", "Pizza"]
    with (out / "businesses.jsonl").open("w", encoding="utf-8") as f:
        for i, bid in enumerate(business_ids):
            attrs = {}
            for key, probability, choices in ATTRS:
                if rng.random() < probability:
                    attrs[key] = rng.choice(choices)
            # A few explicit nulls mimic dirty/heterogeneous source records.
            if attrs and rng.random() < 0.05:
                attrs[rng.choice(list(attrs))] = None
            city, state = rng.choice(cities)
            doc = {
                "business_id": bid,
                "name": f"Sample Place {i:06d}",
                "city": city,
                "state": state,
                "stars": round(rng.uniform(1.0, 5.0) * 2) / 2,
                "review_count": 0,
                "is_open": rng.random() > 0.1,
                "attributes": attrs if rng.random() > 0.08 else None,
                "categories": ", ".join(rng.sample(categories, k=rng.randint(1, 3))) if rng.random() > 0.06 else None,
                "hours": ({"Monday": "09:00-18:00", "Tuesday": "09:00-18:00"} if rng.random() > 0.45 else None),
            }
            f.write(json.dumps(doc, ensure_ascii=False) + "\n")

    start_date = date(2016, 1, 1)
    date_span = (date(2025, 12, 31) - start_date).days
    users = [f"SYNU{i:08d}" for i in range(max(1000, min(args.reviews // 4, 150000)))]
    with (out / "reviews.jsonl").open("w", encoding="utf-8") as f:
        for i in range(args.reviews):
            rdate = start_date + timedelta(days=rng.randrange(date_span + 1))
            doc = {
                "review_id": f"SYNREV{i:010d}",
                "user_id": rng.choice(users),
                "business_id": rng.choice(business_ids),
                "stars": rng.randint(1, 5),
                "date": rdate.isoformat(),
                "text": f"Simulated review {i}. " + rng.choice(["Good service.", "Average food.", "Would visit again.", "Long wait time.", "Friendly staff."]),
                "useful": rng.randint(0, 8),
                "funny": rng.randint(0, 3),
                "cool": rng.randint(0, 5),
                "seq": i,
            }
            f.write(json.dumps(doc, ensure_ascii=False) + "\n")
    (out / "DATASET_NOTE.txt").write_text(
        "SIMULATED DATASET generated by scripts/generate_synthetic.py. Not the Yelp Open Dataset. "
        f"Seed={args.seed}; businesses={args.businesses}; reviews={args.reviews}.\n",
        encoding="utf-8",
    )
    print(f"Generated {args.businesses:,} synthetic businesses and {args.reviews:,} synthetic reviews in {out}")
    print("Use these files only if the Yelp dataset is unavailable, and label the source as simulated in the report.")


if __name__ == "__main__":
    main()
